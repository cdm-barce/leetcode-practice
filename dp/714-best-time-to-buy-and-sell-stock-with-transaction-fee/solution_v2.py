# LeetCode 714. 买卖股票的最佳时机含手续费（中等）
# 套路：状态机 DP —— hold（持有）/ free（空仓），手续费扣在买入时
# 2026-11-08
# 最优代码，O(n) 时间 / O(1) 空间

class Solution:
    def maxProfit(self, prices: list[int], fee: int) -> int:
        hold = float("-inf")     # 初始不可能持有股票，用 -inf 表示"状态不可达"
        free = 0                 # 空仓、一分钱没花，现金为 0

        for p in prices:
            # 今天结束要持有：① 昨天就持有不动 ② 昨天空仓今天买入（付买价 + 手续费）
            new_hold = max(hold, free - p - fee)
            # 今天结束要空仓：① 昨天就空仓不动 ② 昨天持有今天卖出（收卖价）
            new_free = max(free, hold + p)
            # 必须同时更新，否则 new_free 会用到"今天刚买入"的 hold
            hold, free = new_hold, new_free

        return free              # 手里有货不算钱，必须全部卖出才算收益


if __name__ == "__main__":
    s = Solution()

    # 官方示例 1：1 买 8 卖（赚 5），4 买 9 卖（赚 3），合计 8
    assert s.maxProfit([1, 3, 2, 8, 4, 9], 2) == 8

    # 官方示例 2：1 买 7 卖（7-1-3=3），5 买 10 卖（10-5-3=2），合计 6
    assert s.maxProfit([1, 3, 7, 5, 10, 3], 3) == 6

    # fee = 0 时退化成本题 122（无限次交易无成本 → 累加所有上涨）
    assert s.maxProfit([1, 2, 3, 4, 5], 0) == 4

    # 边界：只有一天
    assert s.maxProfit([1], 0) == 0

    # 边界：利润不够付手续费，不交易
    assert s.maxProfit([1, 2], 1) == 0
    assert s.maxProfit([1, 4, 2], 3) == 0

    # 手续费扣掉后仍有赚
    assert s.maxProfit([2, 1, 4], 1) == 2

    # 价格全相同
    assert s.maxProfit([2, 2, 2], 0) == 0

    print("全部用例通过 ✓")


# 踩坑记录：
# 1. 两个状态的定义（关键）：
#    hold = 今天结束时手里有股票，账户现金多少（可以为负，表示"欠钱买入"）
#    free = 今天结束时手里没股票，账户现金多少
#    只记两个数就够，因为后续只关心"有多少钱 + 有没有股票"，不关心"哪天买的"。
# 2. 手续费扣在买入时（也可以扣在卖出时，两者等价，但不能两头都扣）。
#    一笔完整交易的净收益 = 卖价 - 买价 - 手续费，记在哪一端总数不变。
# 3. hold 初值必须是 -inf：表示"初始时不可能持有股票"。
#    如果写 0，等于"白送一只成本 0 的股票"，第一天就能凭空卖出赚钱。
# 4. 必须用 new_ 临时变量同时更新：
#    如果先改 hold 再算 free，free 会用到"今天刚买入"的 hold，
#    算出"当天买当天卖"的假收益。这和链表"先接后断"是同一类问题。
# 5. 返回 free 而不是 max(hold, free)：
#    持有状态里还压着一只没卖的股票（而且手续费已经付了），账面值不算数。
# 6. fee = 0 时退化为 122：因为没有交易成本，"每段小涨都拆开"和"持有到底"
#    收益相同，状态机自然退化成了累加上涨。
#    反过来说：**有成本时"拆开"就不划算了，贪心失效，必须用状态机。**
# 7. 与 309（含冷冻期）的关系：309 需要三个状态（持有/空仓/冷冻），
#    因为"刚卖完不能立刻买"这条约束，光靠两个状态记不住。
