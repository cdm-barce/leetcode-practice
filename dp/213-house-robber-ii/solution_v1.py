# LeetCode 213. 打家劫舍 II（中等）
# 套路：环形拆分 + 线性 DP，max(rob(0..n-2), rob(1..n-1))，O(n) 时间 / O(n) 空间
# 2026-11-13
# 我的解答（v1 数组版，dp 表可打印，方便对照手推）


from typing import List


class Solution:
    def rob(self, nums: List[int]) -> int:
        """
        :param nums: 环形排列的每间房现金
        :return: 不触发报警能偷到的最大金额

        环形约束的破解思路：
        第 0 间和第 n-1 间相邻，最优解里这两间不可能同时被偷，
        所以答案必然落在下面两种情况之一：
          A. 最后一间不偷 → 在 nums[0 .. n-2] 上做线性打家劫舍
          B. 第一间不偷   → 在 nums[1 .. n-1] 上做线性打家劫舍
        两者取较大值，环形问题就此退化成两个 198。
        """
        def _linear(a: List[int]) -> int:
            """198 打家劫舍的线性版本"""
            # 只有一间房，没有邻居可冲突
            if len(a) == 1:
                return a[0]

            # dp[i] = 考虑前 i+1 间房能偷到的最大金额（第 i 间可以不偷）
            dp = [0] * len(a)
            dp[0] = a[0]
            dp[1] = max(a[0], a[1])

            for i in range(2, len(a)):
                # 不偷第 i 间：维持 dp[i-1]
                # 偷第 i 间：跳过一个邻居，累加 dp[i-2]
                dp[i] = max(dp[i - 1], dp[i - 2] + a[i])

            return dp[len(a) - 1]

        n = len(nums)

        # 只有一间房时，nums[:-1] 和 nums[1:] 都是空数组，必须单独处理
        if n == 1:
            return nums[0]

        # 情况 A：不偷最后一间    情况 B：不偷第一间
        return max(_linear(nums[:-1]), _linear(nums[1:]))


if __name__ == "__main__":
    s = Solution()

    # 官方示例
    assert s.rob([2, 3, 2]) == 3, "示例1：首尾相邻，只能偷中间那间"
    assert s.rob([1, 2, 3, 1]) == 4, "示例2：偷第 1、3 间"

    # 边界
    assert s.rob([5]) == 5, "单间房，拆分会得到两个空数组"
    assert s.rob([2, 1]) == 2, "两间房围成圈必然相邻，只能偷大的"
    assert s.rob([0]) == 0, "金额为 0"
    assert s.rob([0, 0]) == 0, "全为 0"

    # n == 3：三间两两相邻，只能偷一间，结果恒为 max
    assert s.rob([1, 2, 3]) == 3
    assert s.rob([2, 7, 9]) == 9, "线性版会给出 11（偷首尾），环形下违规"

    # 关键反例：首尾相邻，不能同时偷
    assert s.rob([2, 1, 1, 2]) == 3, "线性版返回 4（偷首尾），环形下违规"
    assert s.rob([1, 2, 3, 1, 2]) == 5, "线性版返回 6（偷 0 和 4），环形下违规"
    assert s.rob([200, 3, 140, 20, 10]) == 340, "线性版返回 350（首尾全偷）"

    print("全部用例通过 ✓")


# 踩坑记录
# 1. 【环形没处理】直接把 198 的循环 `for i in range(n)` 套过来，会得到线性解，
#    等于允许同时偷第 0 间和第 n-1 间。反例：[2,1,1,2] 线性得 4，环形正确答案是 3。
#    修正思路不是改递推式，而是「枚举哪一边被排除」，把环形降维成两个线性问题。
# 2. 【特判堆砌】先给 n==1/2/3 各写一个 if 提前返回，看似安全，实则每个特判都可能写错，
#    而且掩盖了主逻辑的问题。拆两段之后，n==2 和 n==3 会被通式自动覆盖：
#      n=2 → max(_linear([a]), _linear([b])) = max(a,b)
#      n=3 → max(_linear([a,b]), _linear([b,c])) = max(a,b,c)
#    所以只需要保留 n==1 这一个特判。
# 3. 【n==1 的必要性】nums[:-1] 和 nums[1:] 在 n==1 时都是空数组，会走进 _linear，
#    而 _linear 只处理了 len==1 的情况，会 IndexError。因此这个特判不能用通式替代。
# 4. 【负索引】如果坚持用 dp 数组并从 i=0 开始遍历，dp[i-1]、dp[i-2] 会变成 dp[-1]、dp[-2]，
#    Python 静默指向数组末尾，短数组时结果被污染（同 162 的 nums[-1] 陷阱）。
#    本版 _linear 内部从 i=2 开始遍历，不会越界。
# 5. 空间可压缩：线性部分只依赖前两项，滚动两个变量即可降到 O(1)，见 solution_v2.py。
