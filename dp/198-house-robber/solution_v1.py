# LeetCode 198. 打家劫舍（中等）
# 套路：线性 DP，dp[i] = max(dp[i-1], dp[i-2] + nums[i])，O(n) 时间 / O(n) 空间
# 2026-11-12
# 我的解答（v1 数组版，先把状态和递推跑通）


from typing import List


class Solution:
    def rob(self, nums: List[int]) -> int:
        """
        :param nums: 每间房内藏着的现金
        :return: 不触发报警能偷到的最大金额

        状态定义：dp[i] = 考虑前 i+1 间房（下标 0~i）能偷到的最大金额。
        注意第 i 间房可以不偷，所以 dp[i] 的值不一定包含 nums[i]。
        """
        n = len(nums)

        # 边界：只有一间房，没有邻居冲突，直接拿走
        if n == 1:
            return nums[0]

        dp = [0] * n
        dp[0] = nums[0]                  # 只有一间房，答案就是它自己
        dp[1] = max(nums[0], nums[1])    # 两间房必然相邻，只能二选一

        for i in range(2, n):
            # 分支一：不偷第 i 间 —— 收益维持在第 i-1 间时的最优
            skip = dp[i - 1]

            # 分支二：偷第 i 间 —— 拿走本间现金，再跳过 i-1 接上 dp[i-2]
            take = dp[i - 2] + nums[i]

            dp[i] = max(skip, take)

        return dp[n - 1]


if __name__ == "__main__":
    s = Solution()

    # 官方示例
    assert s.rob([1, 2, 3, 1]) == 4, "示例1：偷 1+3=4"
    assert s.rob([2, 7, 9, 3, 1]) == 12, "示例2：偷 2+9+1=12"

    # 边界
    assert s.rob([5]) == 5, "单间房，走 n==1 分支"
    assert s.rob([5, 10]) == 10, "两间房只能选大的"
    assert s.rob([0, 0, 0]) == 0, "全是 0"

    # 反例：专治「隔一间偷一间」的贪心错觉
    assert s.rob([2, 1, 1, 2]) == 4, "偷第 0、3 间，中间隔了两间"
    # 反例：最后一间不值得偷时，答案不等于 dp[-1] 之外再取 max
    assert s.rob([2, 100, 3]) == 100, "最优解根本没碰最后一间"

    # 顺带核对 dp 表，验证与手推一致
    nums = [2, 7, 9, 3, 1]
    n = len(nums)
    dp = [0] * n
    dp[0], dp[1] = nums[0], max(nums[0], nums[1])
    for i in range(2, n):
        dp[i] = max(dp[i - 1], dp[i - 2] + nums[i])
    assert dp == [2, 7, 11, 11, 12], f"dp 表应为 [2,7,11,11,12]，实际 {dp}"

    print("全部用例通过 ✓")


# 踩坑记录
# 1. 【公式退化】最初写成 dp[i] = max(dp[i-1], dp[i-2])，漏掉了「+ nums[i]」。
#    因为 dp 单调不减，dp[i-1] >= dp[i-2] 恒成立，这个式子会退化成 dp[i] = dp[i-1]，
#    整个数组从第二个元素起全是 nums[0]。自检方法：写完递推式先看它在数学上是否退化，
#    比直接跑测试快得多。
# 2. 【下标含义】dp[i] 有两种定义法：①「前 i+1 间房的最优」（第 i 间可以不偷）；
#    ②「必偷第 i 间时的最大收益」。选 ② 的话最后必须取 max(dp) 而不是 dp[-1]，
#    因为最优解可能压根没碰最后一间（如 nums=[2,100,3] 答案是 100）。
#    本题采用定义 ①，递推式才写得干净。
# 3. 【负索引】若循环从 i=1 开始，dp[i-2] 会变成 dp[-1]，Python 静默取最后一个元素，
#    不报错但结果错（同 162 找峰值的 nums[-1] 陷阱）。所以循环从 i=2 起，
#    并且必须先处理 n==1。
# 4. 【贪心错觉】「隔一间偷一间」是错的：nums=[2,1,1,2] 时答案是 4（偷第 0、3 间），
#    它们中间隔了两间，不存在固定的交替规律。正确性来自「每步都取前 i 间的最优」。
# 5. 空间可压缩：dp[i] 只依赖 dp[i-1] 与 dp[i-2]，滚动两个变量即可降到 O(1)，见 solution_v2.py。
