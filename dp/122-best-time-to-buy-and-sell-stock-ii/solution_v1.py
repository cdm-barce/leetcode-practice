# LeetCode 122. 买卖股票的最佳时机 II（中等）
# 套路：贪心 —— 累加所有「上涨」的相邻差值
# 2026-11-07
# 我的解答（正确，但把边界判断写进了循环体）

class Solution:
    def maxProfit(self, prices: list[int]) -> int:
        profit = 0
        for i in range(len(prices)):
            # i <= len - 2 是为了防止 prices[i+1] 越界
            if i <= len(prices) - 2 and prices[i + 1] > prices[i]:
                profit += prices[i + 1] - prices[i]
        return profit


if __name__ == "__main__":
    s = Solution()

    # 官方示例 1：1 买 5 卖赚 4，3 买 6 卖赚 3，合计 7
    assert s.maxProfit([7, 1, 5, 3, 6, 4]) == 7

    # 官方示例 2：一路涨，1 买 5 卖 = 4（拆成每天买卖也是 4）
    assert s.maxProfit([1, 2, 3, 4, 5]) == 4

    # 官方示例 3：一路跌，不交易
    assert s.maxProfit([7, 6, 4, 3, 1]) == 0

    # 边界：只有一天
    assert s.maxProfit([1]) == 0

    # 边界：两天
    assert s.maxProfit([1, 2]) == 1
    assert s.maxProfit([2, 1]) == 0

    # 波动行情：1→2 赚 1，0→1 赚 1，1→2 赚 1，共 3
    assert s.maxProfit([2, 1, 2, 1, 0, 1, 2]) == 3

    # 全相同
    assert s.maxProfit([3, 3, 3]) == 0

    print("全部用例通过 ✓")


# 踩坑记录：
# 1. 和 121 的关键区别：121 只能交易 1 次，122 可以无限次。
#    121 的「维护最低价」思路在 122 完全失效——因为可以卖了再买，不存在"唯一最低价"。
# 2. 核心转变：不要想"哪天买哪天卖"（方案有无数种），
#    而要问"每一天，我该持有还是空仓"（只有两种状态）。
#    判断依据：明天会涨就持有，明天会跌就空仓。
# 3. 「连续上涨拆开算，收益相同」这个发现是关键：
#    [1,2,3,4,5] 一次性 1 买 5 卖赚 4；
#                每天买卖 (1→2)(2→3)(3→4)(4→5) 也是 1+1+1+1 = 4。
#    既然拆开不亏，那就可以放心地把每段上涨单独计算。
# 4. 正确性证明（面试常追问，必须能说清）：
#    ① 一笔交易（i 买 j 卖）的收益 = p[j] - p[i] = 区间内所有相邻差值之和
#    ② 区间里凡有下跌，这个和就 < 区间内正差值之和（下跌会抵消收益）
#    ③ 所以任何交易组合 ≤ 全局正差值之和          ← 上界
#    ④ 「每段上涨买、每段下跌空仓」正好拿到这个和   ← 可达
#    ⑤ 上界 = 可达 → 这就是最优解
#    反例验证：[1,5,3,6] 一直持有赚 5（6-1），
#              拆开操作赚 7（4+3），差的 2 正好是中间 5→3 的跌幅。
# 5. 边界处理：`i <= len(prices) - 2` 写进循环体是多余的，
#    改成 range(len(prices) - 1) 就不需要判断了（同一个套路见 LC45）。
#    优化版见 solution_v2.py。
# 6. 这题是股票系列里唯一能用贪心解决的。加了手续费（LC714）或冷冻期（LC309）后，
#    「每段上涨都拆开」会变得不划算，贪心失效，必须用 DP。
