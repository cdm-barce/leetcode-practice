# LeetCode 435. 无重叠区间（中等）
# 套路：贪心（我的初版：没排序 + 把覆盖区间取并集）
# 2026-11-09
# 我的思路实现（官方 3 个示例全过，但构造用例全错）

class Solution:
    def eraseOverlapIntervals(self, intervals: list[list[int]]) -> int:
        count = 0
        end = float("-inf")          # 「已覆盖区间」的右边界
        for start, finish in intervals:
            if start < end:          # 重叠
                count += 1
                end = max(end, finish)   # 错 1：把边界扩张成并集（滚雪球）
            else:
                end = finish
        return count
        # 错 2（根因）：全程没有排序


