# 踩坑记录：
# 1. 两个错叠加：
#    ① 没排序 —— intervals 的顺序是随机的，先遇到的区间可能是"又长又早"的坏选择
#    ② 边界取并集（max）—— 一旦用大区间撑开边界，后面所有区间都会被判成重叠
#    正确做法是「边界取最后保留的那个区间的右端」，不扩张。
# 2. **官方三个示例全部通过**，这是最坑的地方：
#    示例 1 的 [1,3] 恰好排在最后、示例 2 全是相同区间、示例 3 本来就无重叠，
#    三种情况都碰不到"大区间排前面"这个致命场景。
#    构造 [[1,100],[2,3],[4,5]] 才能暴露。
# 3. 为什么必须按右端点排序（而不是左端点）：
#    [[1,100],[2,3],[4,5]] 按左端点排还是 [1,100] 在前 → 继续错；
#    按右端点排变成 [[2,3],[4,5],[1,100]] → 先保留小的，最后丢掉大的，正确。
#    直观理解：**区间结束得越早，给后面留的空间越大**。
# 4. 贪心的选择标准是「优先保留结束最早的」，所以排序键是右端点，
#    这和「按开始时间排序」的直觉相反，是这题最核心的考点。
