# LeetCode 435. 无重叠区间（中等）
# ⚠️ 错误示范，不要用这个写法 —— 仅用于记录一个隐蔽的坑
# 2026-11-09
# 相邻比较版：代码只有 2 行，官方 3 个示例全过，但有反例

class Solution:
    def eraseOverlapIntervals(self, intervals: list[list[int]]) -> int:
        intervals.sort(key=lambda x: x[1])
        # 直接比较相邻两个区间：后一个的起点 < 前一个的右端 → 算一次重叠
        return sum(intervals[i][0] < intervals[i - 1][1]
                   for i in range(1, len(intervals)))


if __name__ == "__main__":
    s = Solution()

    # 官方三个示例：全部通过
    assert s.eraseOverlapIntervals([[1, 2], [2, 3], [3, 4], [1, 3]]) == 1
    print("碰巧通过 ✓ 示例 1")

    assert s.eraseOverlapIntervals([[1, 2], [1, 2], [1, 2]]) == 2
    print("碰巧通过 ✓ 示例 2")

    assert s.eraseOverlapIntervals([[1, 2], [2, 3]]) == 0
    print("碰巧通过 ✓ 示例 3")

    # 反例：被丢弃的区间污染了后续判断
    assert s.eraseOverlapIntervals([[1, 5], [2, 3], [4, 6]]) == 2
    print("反面演示 ✓ [[1,5],[2,3],[4,6]] 返回 2，正确答案应为 1")

