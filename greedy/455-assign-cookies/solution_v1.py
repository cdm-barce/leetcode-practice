# 踩坑记录：
# 1. 根因是**没有排序**。贪心策略是「用最小的、能喂饱的饼干，喂胃口最小的孩子」，
#    这个「最小」必须有序列才能确定。不排序就会出现「小胃口抢走大饼干」。
# 2. 反例：[1,3] / [3,2]。不排序时孩子 1 抢走饼干 3，孩子 3 只剩饼干 2，只能喂饱 1 个；
#    排序后：饼干 2 喂孩子 1，饼干 3 喂孩子 3，2 个都能饱。
# 3. s.pop(q2) 会改变列表长度，后续索引全部错位；而且每轮 q2 归零重新扫，
#    复杂度退化到 O(n×m)。双指针天然单调，压根不需要回退。
# 4. 示例数据 [1,2,3]/[1,1] 和 [1,2]/[1,2,3] 本来就有序，所以能通过——
#    这类「数据恰好有序」的用例最容易掩盖排序缺失的问题，测试时要自己造乱序输入。
# 5. 正确写法见 solution_v2.py（排序 + 双指针）和 solution_v3.py（单指针最简版）。
