# LeetCode 88. 合并两个有序数组（简单）
# 套路：三指针从后往前填，O(m+n) 时间 / O(1) 空间 —— 面试官要的答案
# 2026-09-20
# 最优代码

class Solution:
    def merge(self, nums1: list[int], m: int, nums2: list[int], n: int) -> None:
        # 三个指针：
        #   p1 从 nums1 有效部分末尾（m-1）向左扫；
        #   p2 从 nums2 末尾（n-1）向左扫；
        #   p  从 nums1 整体末尾（m+n-1）向左写。
        # 关键：从后往前填，写指针 p 永远走在读指针 p1/p2 右边，
        # 所以直接原地覆盖，不需要任何额外数组 —— O(1) 空间的来源。
        p1, p2, p = m - 1, n - 1, m + n - 1

        # 循环只以 p2 >= 0 为条件：nums2 一旦搬完，nums1 剩下的前缀本来就在正确位置上，不用再搬。
        while p2 >= 0:
            # 【必坑】p1 >= 0 这个判断不能省。Python 的负下标不报错：
            # 若 p1 = -1 时直接写 nums1[p1]，会静默取到数组最后一个元素，结果全错但程序不崩。
            # 用短路与先挡住 p1 < 0 的情况，此时只能取 nums2。
            if p1 >= 0 and nums1[p1] > nums2[p2]:
                nums1[p] = nums1[p1]
                p1 -= 1
            else:
                # 用 > 而非 >=：相等时优先取 nums2 的元素，保持稳定（这题不强制稳定，但写 > 是好习惯）。
                nums1[p] = nums2[p2]
                p2 -= 1
            p -= 1


if __name__ == "__main__":
    s = Solution()

    # 官方示例
    nums1 = [1, 2, 3, 0, 0, 0]
    s.merge(nums1, 3, [2, 5, 6], 3)
    assert nums1 == [1, 2, 2, 3, 5, 6]

    # 边界：nums2 为空（m 覆盖整个 nums1）
    nums1 = [1]
    s.merge(nums1, 1, [], 0)
    assert nums1 == [1]

    # 边界：nums1 有效部分为空（m=0），结果全来自 nums2 —— 重点验证 p1 的负数下标保护
    nums1 = [0]
    s.merge(nums1, 0, [1], 1)
    assert nums1 == [1]

    # 边界：两数组单元素，nums1 末尾更大
    nums1 = [2, 0]
    s.merge(nums1, 1, [1], 1)
    assert nums1 == [1, 2]

    # 两数组元素有重复
    nums1 = [1, 2, 3, 0, 0, 0]
    s.merge(nums1, 3, [2, 2, 2], 3)
    assert nums1 == [1, 2, 2, 2, 2, 3]

    # 负数
    nums1 = [-1, 0, 0, 3, 0, 0, 0]
    s.merge(nums1, 4, [-1, -1, 2], 3)
    assert nums1 == [-1, -1, -1, 0, 0, 2, 3]

    print("全部用例通过 ✓")

# 踩坑记录：
# 1. 【负下标静默】这是本题最阴的坑。Python 里 nums1[-1] 不报错，会取到最后一个元素。
#    所以 p1 = -1（nums1 有效部分已搬完）时必须用 p1 >= 0 挡住，否则拿到的是错误数据且程序照常跑完。
# 2. 【循环条件选 p2】用 while p2 >= 0 而不是 while p1 >= 0：nums2 搬完后 nums1 前缀已是正确顺序，
#    提前收工能少做无用功；反过来若以 p1 为条件，nums1 搬完时 nums2 还剩元素就需要额外处理。
# 3. 【> vs >=】相等时优先取 nums2（写 >），保证稳定性；本题不强制，但稳定是好习惯且无代价。
# 4. 【为何从后往前】写指针 p 起点在数组最右，每轮向左，永远不回头踩到还没读的 p1/p2 指向的位置；
#    若从前往后则需要额外数组（写会追上前面的读），这就是 O(1) 空间的关键。
# 5. 【题眼】nums1 后 n 格是免费空间 + 输入已有序 = 从后往前填。这是本题唯一考点，务必记住。
