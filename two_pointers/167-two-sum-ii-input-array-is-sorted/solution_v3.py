# LeetCode 167. 两数之和 II - 输入有序数组（中等）
# 套路：对撞双指针，O(n) 时间 / O(1) 额外空间 —— 已通过
# 2026-09-19
# 我的解答（正确解，内部 0-based，返回时 +1）


class Solution:
    def twoSum(self, numbers: list[int], target: int) -> list[int]:
        L = 0                      # 左指针指向第一个元素（Python 下标从 0 起）
        R = len(numbers) - 1       # 右指针指向最后一个元素：长度 - 1 才是最大合法下标

        # 循环不变量：答案（若存在）始终落在闭区间 [L, R] 内
        while L < R:
            sum = numbers[L] + numbers[R]

            if sum == target:
                # 题面要求 1-based 位置，这里统一做唯一一次换算：0-based 下标 + 1
                return [L + 1, R + 1]

            elif sum < target:
                # 和偏小。此刻 R 已经是当前 L 能配到的最大值，
                # 动 R 只会让和更小或不变 → 只能丢掉当前位置的 L，换一个更大的左值
                L += 1
            else:
                # 和偏大，对称地丢掉 R，换一个更小的右值
                R -= 1

        return []                  # 题目保证恰有一组解，这行实际不可达，仅作兜底


if __name__ == "__main__":
    s = Solution()
    # 官方示例 1
    assert s.twoSum([2, 7, 11, 15], 9) == [1, 2]
    # 官方示例 2
    assert s.twoSum([2, 3, 4], 6) == [1, 3]
    # 官方示例 3：负数与 0
    assert s.twoSum([-1, 0], -1) == [1, 2]
    # 最短输入：只有两个元素
    assert s.twoSum([1, 2], 3) == [1, 2]
    # 答案在末尾：必须一路丢掉左边的指针才能找到
    assert s.twoSum([1, 2, 3, 4, 5, 9], 14) == [5, 6]
    # 答案在开头：验证 numbers[0] 真的被用上了（v2 的 L = 1 会漏掉它）
    assert s.twoSum([2, 7, 11, 15], 13) == [1, 3]
    # 全负数
    assert s.twoSum([-5, -3, -1], -8) == [1, 2]
    # 含重复值
    assert s.twoSum([0, 0, 3, 4], 0) == [1, 2]
    print("全部用例通过 ✓")

# 踩坑记录：
# 1. 本题两次报错都出在「下标」上，跟双指针这个算法思路本身毫无关系：
#    v1 是语言 API 记错（numbers.len），v2 是长度当成了下标（len vs len - 1）。
#    思路对了，代码照样崩 —— 这就是基础语法不熟的真实代价。
# 2. 【核心认知】题面写的「下标从 1 开始」只约束**返回的答案**；
#    代码里取元素永远按 Python 的 0-based 走，题面说了不算。两套编号之间必须显式换算一次。
#    本版选择「内部全程 0-based + 只在 return 时 +1」，换算只出现一次，最不容易漏；
#    另一种等价写法是内部全程 1-based、取值时写 numbers[L - 1]，换算出现多次，更易翻车。
# 3. 【为什么这么动指针】sum < target 时不动 R：因为 R 已经是当前 L 能配到的最大值，
#    动它只会让和更小或不变，所以只能丢 L。sum > target 时对称地丢 R。
#    每一步都能永久排除一个位置 → 总步数 O(n)。
# 4. 【为什么不用哈希表】哈希表时间同样是 O(n)，但空间 O(n)，
#    不满足题目「只能使用常量级额外空间」的进阶要求；二分法则是 O(n log n)，更差。
#    所以 O(n) / O(1) 就是本题的理论最优，没有更优解。
# 5. 【命名】变量名 sum 遮蔽了内置函数 sum()。本题没调用 sum() 所以无碍，
#    但换个需要求和的题就会踩坑，建议以后叫 cur 或 s。
# 6. 与 LC 15 三数之和、LC 11 盛最多水的容器是同一个套路（排序/有序 + 对撞双指针），
#    区别只在「什么时候移动哪一侧」的判断条件。
